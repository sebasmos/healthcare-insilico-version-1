// Pre-bundles Cornerstone3D into viewers/web/vendor/ as plain ES modules.
// This is the one place a bundler runs; the output is committed so that
// `npm run dev` still needs no build. Run it after `npm install`:
//   npm run vendor
// It writes viewers/web/vendor/cornerstone.js (core, tools, the DICOM image loader
// and the NIfTI volume loader), the decoder web worker, the WebAssembly
// codecs, and viewers/web/vendor/README.md with package versions and licences.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { REPO_ROOT } from '../platform/server/db/index.mjs';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');
const out = path.join(REPO_ROOT, 'viewers', 'web', 'vendor');
const entryDir = path.join(REPO_ROOT, 'scripts', 'vendor-entry');
fs.mkdirSync(out, { recursive: true });
fs.mkdirSync(path.join(out, 'codecs'), { recursive: true });
fs.mkdirSync(entryDir, { recursive: true });

const entry = path.join(entryDir, 'cornerstone.js');
fs.writeFileSync(entry, [
  '// Generated by scripts/vendor.mjs. The four Cornerstone3D packages as one ES module for the browser.',
  "export * as core from '@cornerstonejs/core';",
  "export * as tools from '@cornerstonejs/tools';",
  "export * as dicomImageLoader from '@cornerstonejs/dicom-image-loader';",
  "export * as niftiLoader from '@cornerstonejs/nifti-volume-loader';",
  "// vtk.js plane, for the 3D clipping box in the volume layout.",
  "export { default as vtkPlane } from '@kitware/vtk.js/Common/DataModel/Plane';",
  '',
].join('\n'));

// The Emscripten glue in the codec packages and a few transitive dependencies import Node built-ins behind environment checks the browser never takes; a small shim stands in for them so no require() is left in the bundle.
const NODE_BUILTINS = ['fs', 'path', 'module', 'crypto', 'worker_threads', 'events', 'stream', 'buffer', 'util', 'os', 'url', 'node:fs', 'node:path', 'node:url', 'node:events'];
const shimPlugin = { name: 'node-shim', setup(build) { build.onResolve({ filter: new RegExp(`^(${NODE_BUILTINS.map((n) => n.replace('/', '\\/')).join('|')})$`) }, () => ({ path: path.join(entryDir, 'node-shim.js') })); } };
const common = { bundle: true, format: 'esm', platform: 'browser', target: ['es2022'], minify: true, sourcemap: false, legalComments: 'none', logLevel: 'warning', define: { 'process.env.NODE_ENV': '"production"', 'process.platform': '"browser"' }, loader: { '.wasm': 'file', '.svg': 'dataurl' }, assetNames: 'codecs/[name]', plugins: [shimPlugin] };
const main = await esbuild.build({ ...common, entryPoints: [entry], outfile: path.join(out, 'cornerstone.js'), metafile: true });
const pkgDir = (name) => path.dirname(require.resolve(`${name}/package.json`));
const workerSrc = path.join(pkgDir('@cornerstonejs/dicom-image-loader'), 'dist', 'esm', 'decodeImageFrameWorker.js');
await esbuild.build({ ...common, entryPoints: [workerSrc], outfile: path.join(out, 'decodeImageFrameWorker.js') });
// The tools package's compute worker is referenced as ../workers/computeWorker.js; it lives beside the bundle here.
const computeWorker = path.join(pkgDir('@cornerstonejs/tools'), 'dist', 'esm', 'workers', 'computeWorker.js');
if (fs.existsSync(computeWorker)) await esbuild.build({ ...common, entryPoints: [computeWorker], outfile: path.join(out, 'computeWorker.js') });
// OpenSeadragon (pathology slide viewer, plan E) as its own ES module.
const osdEntry = path.join(entryDir, 'openseadragon.js');
fs.writeFileSync(osdEntry, "// Generated by scripts/vendor.mjs. OpenSeadragon as an ES module for the browser.\nimport OpenSeadragon from 'openseadragon';\nexport default OpenSeadragon;\nexport { OpenSeadragon };\n");
await esbuild.build({ ...common, entryPoints: [osdEntry], outfile: path.join(out, 'openseadragon.js') });
const bundlePath = path.join(out, 'cornerstone.js');
fs.writeFileSync(bundlePath, fs.readFileSync(bundlePath, 'utf8').replaceAll('"../workers/computeWorker.js"', '"./computeWorker.js"'));
// Core's own compute workers, when the installed version ships them as separate files.
const coreDist = pkgDir('@cornerstonejs/core');
for (const file of fs.readdirSync(path.join(coreDist, 'dist', 'esm'), { recursive: true }).filter((f) => /Worker\.js$/.test(String(f)))) {
  await esbuild.build({ ...common, entryPoints: [path.join(coreDist, 'dist', 'esm', String(file))], outfile: path.join(out, path.basename(String(file))) });
}
// Every WebAssembly codec the loader may ask for, by its file name.
for (const pkg of ['codec-openjpeg', 'codec-openjph', 'codec-charls', 'codec-libjpeg-turbo-8bit', 'codec-libjxl']) {
  const dir = path.join(REPO_ROOT, 'node_modules', '@cornerstonejs', pkg, 'dist');
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.wasm'))) fs.copyFileSync(path.join(dir, f), path.join(out, 'codecs', f));
}

const versions = ['@cornerstonejs/core', '@cornerstonejs/tools', '@cornerstonejs/dicom-image-loader', '@cornerstonejs/nifti-volume-loader', '@kitware/vtk.js', 'openseadragon', 'esbuild'].map((p) => { try { const j = require(`${p}/package.json`); return { name: p, version: j.version, license: j.license || 'see package' }; } catch { return { name: p, version: 'not installed', license: '' }; } });
const sizes = fs.readdirSync(out).filter((f) => f.endsWith('.js')).map((f) => `${f}: ${(fs.statSync(path.join(out, f)).size / 1024 / 1024).toFixed(2)} MB`);
fs.writeFileSync(path.join(out, 'README.md'), [
  '# Vendored browser libraries',
  '',
  'Generated by `npm run vendor` (`scripts/vendor.mjs`, esbuild). Committed as plain ES modules so `npm run dev` needs no build. No CDN and no telemetry: the image loader reads only from this server\'s DICOMweb routes.',
  '',
  '| Package | Version | Licence |', '|---|---|---|', ...versions.map((v) => `| ${v.name} | ${v.version} | ${v.license} |`),
  '', '## Files', '', ...sizes.map((s) => `- ${s}`), `- codecs/: ${fs.readdirSync(path.join(out, 'codecs')).length} WebAssembly codec files (JPEG, JPEG-LS, JPEG 2000, HTJ2K, JPEG XL)`,
  '', 'Licences: Cornerstone3D packages are MIT; vtk.js is BSD-3-Clause; OpenSeadragon is BSD-3-Clause; the codec packages carry their upstream licences (OpenJPEG BSD-2-Clause, CharLS BSD-3-Clause, libjpeg-turbo IJG and BSD, OpenJPH BSD-2-Clause, libjxl BSD-3-Clause). See each package in node_modules for the full text.', '',
].join('\n'));
console.log(`Vendored to ${path.relative(REPO_ROOT, out)}: ${sizes.join(', ')}`);
console.log(`Inputs bundled: ${Object.keys(main.metafile.inputs).length} files`);
