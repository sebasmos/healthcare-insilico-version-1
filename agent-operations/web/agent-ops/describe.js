// Plain-English names for what a step did, shared by the run page and the trace viewer.
// What a step did, in words a clinician would use.
export const THING = { ImagingStudy: 'imaging study', DiagnosticReport: 'report', Patient: 'patient chart', ServiceRequest: 'order', Communication: 'message', Task: 'task', MedicationRequest: 'medication', Provenance: 'provenance record', Observation: 'result', DocumentReference: 'note', Condition: 'problem', AllergyIntolerance: 'allergy', Encounter: 'visit', Appointment: 'appointment', MedicationDispense: 'dispense record', DetectedIssue: 'pharmacy check', Location: 'bed or location', MedicationAdministration: 'medication administration', CarePlan: 'care plan', Goal: 'goal', Procedure: 'procedure or education record', Specimen: 'specimen', Device: 'home device' };
export function describeAction(type, args = {}) {
  const thing = THING[args.type] || args.type || 'record';
  switch (type) {
    case 'run.start': return 'Run started';
    case 'run.end': return `Run ended (${args.reason || 'completed'})`;
    case 'run.pause': return 'Run paused';
    case 'run.resume': return 'Run resumed';
    case 'fhir.read': case 'chart.open': return `Read ${thing}`;
    case 'fhir.search': return `Looked up ${thing}s`;
    case 'fhir.create': return `Wrote a new ${thing}`;
    case 'fhir.update': return `Updated ${thing}`;
    case 'fhir.transition': return `Changed ${thing} from ${args.from} to ${args.to}`;
    case 'system.derive': return `System recorded ${thing}`;
    case 'proposal.create': return 'Proposal shown to clinicians';
    case 'proposal.auto-apply': return 'Draft applied without asking (unsigned)';
    case 'proposal.view': return 'Clinician saw the proposal';
    case 'proposal.accept': return 'Clinician accepted the proposal';
    case 'proposal.edit': return 'Clinician edited, then accepted';
    case 'proposal.reject': return 'Clinician rejected the proposal';
    case 'safety.block': return `Order stopped by a safety alert (${(args.alerts || []).join(', ')})`;
    case 'safety.override': return args.alert === 'unverified-stat' ? 'Emergency override: STAT medication given before pharmacy verification' : `Safety alert overridden (${args.alert || ''})`;
    case 'episode.create': return 'Episode recorded';
    case 'horizon.check': return `Outcome checked at: ${(args.horizons || []).join(', ')}`;
    case 'redteam.plant': return `Scenario chart loaded (${args.resources} records)`;
    case 'envelope.reject': return `Refused by the safety envelope (${args.rule})`;
    case 'role.refuse': return `Refused: a ${args.role || 'role'} may not ${args.interaction || 'write'} ${thing}`;
    case 'order.cosign': return `Co-signed a nurse-entered ${thing}`;
    case 'image.open': return 'Opened the study for reading';
    case 'image.annotate': return 'Saved a measurement drawn on the images';
    case 'slide.open': return 'Opened a whole-slide image';
    case 'slide.store': return `Stored a whole-slide image (${args.levels ?? ''} levels)`;
    case 'slide.annotate': return 'Saved an annotation drawn on a slide';
    case 'slide.annotation.remove': return 'Removed a slide annotation';
    case 'case.open': return 'Opened a pathology case for sign-out';
    case 'case.unlock': return 'Released the pathology case lock';
    case 'pathology.accession': return 'Accessioned a pathology case';
    case 'pathology.receive': return 'Received a pathology case';
    case 'pathology.part': return 'Added a part to a pathology case';
    case 'pathology.block': return 'Added a block to a pathology case';
    case 'pathology.slide': return 'Added a slide to a pathology case';
    case 'pathology.gross': return 'Entered the gross description';
    case 'pathology.addon': return 'Requested more histology work (recut, levels or stain)';
    case 'pathology.addon-done': return 'Completed a histology request';
    case 'pathology.process': return 'Case moved to in process';
    case 'pathology.order-note': return 'Noted the accession on the pathology order';
    case 'image.annotation.remove': return 'Removed a saved measurement';
    case 'dicom.store': return `Stored ${args.instances ?? ''} DICOM image(s)${args.patientOverride ? ` attached to ${args.patientOverride} (header patient id ${args.headerPatientId})` : ''}`;
    case 'import.fhir': return `Imported ${args.file || 'a FHIR file'} (${args.written ?? 0} written)`;
    case 'import.patient': return `Registered a synthetic patient for imported ${args.kind || 'source'} data (${args.mrn || ''})`;
    case 'import.ecg': return `Imported ECG record ${args.record || ''} (${args.leads ?? 0} leads)`;
    case 'capture.think-aloud': return `Think-aloud note (${args.length} characters, kept separately)`;
    case 'capture.why': return `Answered "why?"${args.about ? ` about ${args.about}` : ''} (kept separately)`;
    case 'capture.dictation': return `Dictated into ${args.field} (transcript kept separately)`;
    case 'capture.content.delete': return `Written content deleted (${(args.contentIds || []).length}): ${args.reason}`;
    case 'capture.content.read': return 'Written content shown to a reviewer';
    case 'capture.policy': return `Recording policy changed: written content ${args.contentCapture ? 'allowed' : 'not allowed'}`;
    case 'annotation.project.create': return `Labelling project created (${args.items} items)`;
    case 'annotation.project.close': return 'Labelling project closed';
    case 'annotation.label': return 'Labelled an item';
    case 'annotation.adjudicate': return 'Settled a disagreement (final label)';
    case 'annotation.skip': return `Skipped ${args.item} for now`;
    case 'annotation.export': return `Exported labels (${args.format}, de-identified)`;
    case 'pharmacy.migrate': return `Tagged ${args.count ?? ''} active medication order(s) as verified before pharmacy verification existed`;
    case 'pharmacy.open': return `Opened a medication order for verification${args.tookOver ? ` (took over from ${args.tookOver})` : ''}`;
    case 'pharmacy.unlock': return 'Released the verification lock on a medication order';
    case 'pharmacy.check': return 'Pharmacy check recorded on a medication order';
    case 'pharmacy.check.close': return 'Pharmacy check closed with the decision';
    case 'pharmacy.verify': return `Pharmacist verified the medication order (${args.minutes ?? '?'} min, ${args.priority || 'routine'})`;
    case 'pharmacy.verify-change': return `Pharmacist verified the medication order with a change (${args.change ? Object.entries(args.change).filter(([, v]) => v != null && v !== '').map(([k, v]) => `${k} ${v}`).join(', ') : ''})`;
    case 'pharmacy.reject': return `Pharmacist rejected the medication order: ${args.reason || ''}`;
    case 'pharmacy.query': return 'Pharmacist queried the prescriber; the order waits';
    case 'pharmacy.query.send': return 'Pharmacy question sent to the prescriber';
    case 'pharmacy.notice': return 'Pharmacy notice sent to the prescriber\'s Inbox';
    case 'pharmacy.answer': return 'Prescriber answered the pharmacy question';
    case 'pharmacy.answer.send': return 'Answer to pharmacy sent';
    case 'pharmacy.dispense': return 'Dispense started (preparation)';
    case 'pharmacy.dispense.fill': return 'Dispense filled (in progress)';
    case 'pharmacy.dispense.complete': return 'Dispense completed and checked';
    case 'ui.click': return `Clicked ${args.target || 'a control'}`;
    case 'ui.change': return `Changed ${args.field || 'a field'}`;
    case 'ui.nav': return `Went to ${args.route || 'another screen'}`;
    case 'ui.context': return 'Switched patient';
    case 'ui.viewer': return `Viewer: ${args.viewer?.action || 'action'}`;
    case 'ui.focus': return `Moved to ${args.target || 'a control'}`;
    case 'ui.scroll': return 'Scrolled';
    case 'ui.submit': return `Submitted ${args.target || 'a form'}`;
    case 'bed.seed': return `Hospital layout loaded (${args.written ?? 0} locations written)`;
    case 'bed.assign': return `Assigned ${args.display || args.bed || 'a bed'}${typeof args.waitedMinutes === 'number' ? ` after ${args.waitedMinutes} min waiting` : ''}`;
    case 'bed.transfer': return `Transferred from ${args.fromDisplay || args.from || 'a bed'} to ${args.display || args.to || 'a bed'}${args.reason ? ` (${args.reason})` : ''}`;
    case 'bed.discharge': return `Discharged${args.display ? ` from ${args.display} (bed to cleaning)` : ''}`;
    case 'bed.clean': return `Marked ${args.display || args.bed || 'a bed'} clean${typeof args.dirtyMinutes === 'number' ? ` after ${args.dirtyMinutes} min` : ''}`;
    case 'bed.block': return `Blocked ${args.display || args.bed || 'a bed'}: ${args.reason || ''}`;
    case 'bed.unblock': return `Unblocked ${args.display || args.bed || 'a bed'}: ${args.reason || ''}`;
    case 'bed.reserve': return `Reserved ${args.display || args.bed || 'a bed'}${args.encounter ? ' for a patient' : ''}`;
    case 'bed.release': return `Released the reservation on ${args.display || args.bed || 'a bed'}`;
    case 'bed.request': return `Bed requested${args.unit ? ` in ${args.unit.replace(/^unit-/, '').toUpperCase()}` : ''}${args.transfer ? ' (transfer)' : ''}${args.isolation ? ', isolation' : ''}`;
    case 'mar.given': return `Gave a dose of ${args.medication || 'medication'}${args.late ? ' (late)' : ''}`;
    case 'mar.started': return `Started ${args.medication || 'an infusion'}`;
    case 'mar.held': return `Held a dose of ${args.medication || 'medication'}`;
    case 'mar.refused': return `Patient refused ${args.medication || 'a dose'}`;
    case 'mar.not-given': return `Dose not given: ${args.medication || 'medication'}`;
    case 'mar.entered-in-error': return 'Administration record marked entered in error';
    case 'mar.prn-follow-up': return 'Follow-up assessment task after a PRN dose';
    case 'io.record': return 'Recorded intake or output';
    case 'order.acknowledge': return 'Nurse acknowledged an order';
    case 'education.record': return 'Recorded patient education';
    case 'careplan.evaluate': return 'Evaluated the care plan';
    case 'ecg.record': return 'Recorded a 12-lead ECG';
    case 'ecg.measure': return 'Edited ECG measurements';
    case 'ecg.interpret': return 'Wrote the ECG interpretation';
    case 'specimen.collect': return 'Collected a specimen';
    case 'specimen.in-transit': return 'Specimen sent to the laboratory';
    case 'specimen.received': return 'Specimen received and accessioned';
    case 'specimen.in-process': return 'Specimen in process';
    case 'specimen.resulted': return 'Specimen resulted (preliminary)';
    case 'specimen.verified': return 'Specimen results verified';
    case 'specimen.corrected': return 'Specimen result corrected';
    case 'specimen.rejected': return `Specimen rejected${args.reason ? ` (${args.reason})` : ''}`;
    case 'specimen.recollect-task': return 'Recollection task sent to the nurse';
    case 'lab.result': return 'Entered a preliminary result';
    case 'lab.autoverify': return 'Result auto-verified by rule';
    case 'lab.verify': return 'Verified a result';
    case 'lab.correct': return 'Corrected a verified result';
    case 'lab.phone': return `Phoned a critical value${args.to ? ` to ${args.to}` : ''}`;
    case 'lab.qc': return 'Recorded a quality-control result';
    case 'lab.autoverify-rules': return 'Changed the auto-verification rules';
    case 'lab.comment': return 'Verification comment';
    case 'hl7.receive': return `HL7 ${args.type || 'message'} accepted (${args.controlId || ''})`;
    case 'hl7.reject': return `HL7 ${args.type || 'message'} refused: ${args.reason || ''}`;
    case 'hl7.send': return `HL7 ${args.type || 'message'} built for sending`;
    case 'hl7.result': return 'Result received over HL7';
    case 'hl7.unsolicited-order': return 'Unsolicited order created from an HL7 result';
    case 'hl7.admit': return 'Admitted over HL7 ADT';
    case 'hl7.register': return 'Registered over HL7 ADT';
    case 'hl7.update': return 'Demographics updated over HL7 ADT';
    case 'hl7.cancel-admit': return 'Admission cancelled over HL7 ADT';
    case 'hl7.cancel-discharge': return 'Discharge cancelled over HL7 ADT (encounter reinstated)';
    case 'rpm.enrol': return 'Enrolled in remote monitoring';
    case 'rpm.end': return 'Remote monitoring programme ended';
    case 'rpm.device': return 'Home device registered';
    case 'rpm.threshold': return 'Monitoring threshold set';
    case 'rpm.reading': return 'Home reading recorded';
    case 'rpm.alert': return 'Monitoring alert opened';
    case 'rpm.acknowledge': return `Monitoring alert acknowledged${typeof args.minutes === 'number' ? ` after ${args.minutes} min` : ''}`;
    case 'rpm.snooze': return `Monitoring alert snoozed: ${args.reason || ''}`;
    case 'rpm.escalate': return 'Monitoring alert escalated to the physician';
    case 'rpm.call': return `Called ${args.to || 'the patient'} about a monitoring alert`;
    case 'rpm.message': return 'Messaged the patient about a monitoring alert';
    case 'rpm.close': return `Monitoring alert closed: ${args.outcome || ''}`;
    case 'model.call': return `Model call (${args.adapter || ''}${args.model ? `, ${args.model}` : ''}${typeof args.latencyMs === 'number' ? `, ${args.latencyMs} ms` : ''}${args.error ? `, failed: ${args.error}` : ''})`;
    case 'model.refuse': return `External model refused: ${args.reason || ''}`;
    case 'cds.call': return `CDS ${args.hook || ''} call to ${args.service || ''}: ${args.status || ''} (${args.cards ?? 0} cards)`;
    case 'cds.card': return `CDS card shown (${args.indicator || 'info'}): ${args.summary || ''}`;
    case 'cds.accept': return `CDS suggestion accepted (${args.service || ''})`;
    case 'cds.dismiss': return `CDS card dismissed${args.overrideReason ? `: ${args.overrideReason}` : ''}`;
    case 'cds.register': return `CDS service registered: ${args.url || ''}`;
    default: return type;
  }
}
export const describe = (step) => describeAction(step.did.type, step.did.args || {});
